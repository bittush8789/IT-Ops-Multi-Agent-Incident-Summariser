"""Pydantic schemas for the Incident Report, Timeline, and Post-Incident Review (PIR)."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class TimelineEntry(BaseModel):
    """An individual verified event in the chronological incident timeline."""
    timestamp: datetime = Field(..., description="ISO timestamp of the event")
    event_type: str = Field(..., description="ALERT, DEPLOYMENT, ERROR_SURGE, INVESTIGATION, MITIGATION, RESOLUTION")
    source: str = Field(..., description="Origin: LogAnalyst, ChangeAnalyst, Monitoring, SRE")
    description: str = Field(..., description="Accurate description based strictly on observed evidence")
    evidence_reference: str = Field(..., description="Pointer to log line, commit SHA, or metric")
    is_inferred: bool = Field(default=False, description="Flag indicating if the event is deduced rather than directly logged")


class RootCauseHypothesis(BaseModel):
    """Evidence-backed candidate explanation for the incident."""
    hypothesis: str = Field(..., description="Plausible technical root cause statement")
    likelihood: str = Field(..., description="HIGH, MEDIUM, or LOW")
    supporting_evidence: List[str] = Field(default_factory=list, description="Verified facts and references supporting this hypothesis")
    contradicting_evidence: List[str] = Field(default_factory=list, description="Observed facts or timing that challenge this hypothesis")
    unknowns: List[str] = Field(default_factory=list, description="Missing telemetry or data required to prove or disprove")


class ActionItem(BaseModel):
    """Corrective or preventive action recommendation."""
    title: str = Field(..., description="Action title")
    description: str = Field(..., description="Details of remediation or preventative engineering")
    priority: str = Field(default="MEDIUM", description="P0, P1, P2, or P3")
    owner_team: str = Field(default="SRE", description="Team accountable for implementation")
    action_type: str = Field(default="PREVENTION", description="REMEDIATION, DETECTION, PREVENTION, or RUNBOOK")


class PostIncidentReview(BaseModel):
    """Structured Post-Incident Review (PIR) artifact."""
    summary: str = Field(..., description="Brief overview of the incident narrative")
    impact: str = Field(..., description="Quantified or qualified user and business impact")
    contributing_factors: List[str] = Field(default_factory=list, description="Technical and procedural factors")
    lessons_learned: List[str] = Field(default_factory=list, description="What went well, what could be improved")
    timeline: List[TimelineEntry] = Field(default_factory=list, description="Official sequence of events")
    follow_up_actions: List[ActionItem] = Field(default_factory=list, description="Preventative and corrective tasks")


class IncidentReportBase(BaseModel):
    """Incident report fields generated by the Report Writer Agent."""
    executive_summary: str = Field(..., description="High-level briefing for leadership and stakeholders")
    impact_summary: str = Field(..., description="Quantified customer or business impact supported by evidence")
    timeline: List[TimelineEntry] = Field(default_factory=list, description="Chronological timeline of incident")
    root_cause_hypotheses: List[RootCauseHypothesis] = Field(default_factory=list, description="Evaluated root causes")
    recommendations: List[ActionItem] = Field(default_factory=list, description="Immediate and long-term recommendations")
    post_incident_review: PostIncidentReview = Field(..., description="Comprehensive PIR document")
    confidence_notes: str = Field(..., description="Analysis of evidence completeness, conflicts, and gaps")


class IncidentReportCreate(IncidentReportBase):
    """Schema for persisting an incident report."""
    incident_id: int


class IncidentReportResponse(IncidentReportBase):
    """Schema for incident report API response."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    incident_id: int
    created_at: datetime
    updated_at: datetime


class ReportRegenerateRequest(BaseModel):
    """Request payload to force report regeneration."""
    include_historical_context: bool = Field(default=True, description="Whether to include pgvector historical matches")
    custom_guidance: Optional[str] = Field(default=None, description="Additional context or focus for the Report Writer")
